use std::{env, fs, path::Path, path::PathBuf};

// Editor plugins, as quartz has them: every folder under src/plugin/ with a mod.rs is compiled
// in (with `#[cfg(plugin_<name>)]` true), and nothing else needs to know. Delete a folder and its
// plugin is gone; no Cargo [features] are involved.
//
// A plugin that works with another program does not make it a build dependency either. The
// PathForge plugin previews PathForge backgrounds by loading PathForge's runtime library (its C
// interface) when a preview opens, so this editor builds whether or not PathForge is installed;
// here we only look for a PathForge checkout, to tell the plugin where its library is built.
fn main() {
    let manifest_dir = PathBuf::from(env::var("CARGO_MANIFEST_DIR").unwrap());
    let plugin_dir = manifest_dir.join("src").join("plugin");
    println!("cargo:rerun-if-changed={}", plugin_dir.display());

    let mut plugins: Vec<(String, String)> = Vec::new();
    if let Ok(entries) = fs::read_dir(&plugin_dir) {
        let mut entries: Vec<_> = entries.flatten().collect();
        entries.sort_by_key(|e| e.file_name()); // deterministic order
        for entry in entries {
            let path = entry.path();
            let mod_rs = path.join("mod.rs");
            if path.is_dir() && mod_rs.exists() {
                let name = path.file_name().unwrap().to_string_lossy().into_owned();
                let abs_path = mod_rs.to_string_lossy().replace('\\', "\\\\");
                plugins.push((name, abs_path));
            }
        }
    }
    for (name, _) in &plugins {
        println!("cargo:rustc-cfg=plugin_{name}");
        println!("cargo:rustc-check-cfg=cfg(plugin_{name})");
    }
    // Every plugin's cfg is known even when its folder is gone (no unexpected_cfgs warnings).
    println!("cargo:rustc-check-cfg=cfg(plugin_path_forge)");

    let out_dir = env::var("OUT_DIR").unwrap();
    let mut mods = String::from("// Auto-generated by build.rs — do not edit.\n");
    for (name, abs_path) in &plugins {
        mods.push_str(&format!("#[cfg(plugin_{name})] #[path = \"{abs_path}\"] pub mod {name};\n"));
    }
    fs::write(Path::new(&out_dir).join("plugin_mods.rs"), mods).unwrap();

    if plugins.iter().any(|(n, _)| n == "path_forge") {
        find_path_forge(&manifest_dir);
    }
}

/// Where a PathForge checkout is: `PATH_FORGE_DIR`, or a `path_forge` folder beside this one or
/// beside the folder it sits in (synful_quartz/quartz_forge next to path_forge). Passed to the
/// plugin as `QF_PATH_FORGE_DIR` (empty when there is none: the plugin then looks only beside
/// the editor and in `PATH_FORGE_RUNTIME`).
fn find_path_forge(manifest_dir: &Path) {
    println!("cargo:rerun-if-env-changed=PATH_FORGE_DIR");
    let mut tries: Vec<PathBuf> = Vec::new();
    if let Ok(d) = env::var("PATH_FORGE_DIR") { tries.push(PathBuf::from(d)); }
    for up in [manifest_dir.parent(), manifest_dir.parent().and_then(Path::parent)].into_iter().flatten() {
        tries.push(up.join("path_forge"));
    }
    let found = tries.into_iter().find(|d| d.join("runtime").join("Cargo.toml").exists());
    let dir = found.as_ref().map(|d| d.canonicalize().unwrap_or_else(|_| d.clone()));
    println!("cargo:rustc-env=QF_PATH_FORGE_DIR={}", dir.as_ref().map(|d| d.to_string_lossy().into_owned()).unwrap_or_default());
    if let Some(d) = &dir {
        let lib = format!("{}path_forge_runtime{}", env::consts::DLL_PREFIX, env::consts::DLL_SUFFIX);
        let built = ["release", "debug"].iter().any(|p| d.join("target").join(p).join(&lib).exists());
        if !built {
            println!(
                "cargo:warning=PathForge found at {} but its runtime library is not built, so the editor's PathForge preview will be off until it is: run `cargo build --release -p path_forge_runtime` there",
                d.display()
            );
        }
    }
}
